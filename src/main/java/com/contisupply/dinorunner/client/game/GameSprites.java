	/** Parses a '#'-grid into a boolean bitmap. Throws early and loudly on ragged rows. */
	public static boolean[][] parse(String... rows) {
		int w = rows[0].length();
		boolean[][] grid = new boolean[rows.length][w];
		for (int y = 0; y < rows.length; y++) {
			if (rows[y].length() != w) {
				throw new IllegalArgumentException(
						"Sprite row " + y + " is " + rows[y].length() + " chars, expected " + w);
			}
			for (int x = 0; x < w; x++) {
				grid[y][x] = rows[y].charAt(x) == '#';
			}
		}
		return grid;
	}

